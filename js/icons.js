// Helper to inject icons into elements with data-icon attribute
function renderRealmIcons() {
  document.querySelectorAll('[data-realm-icon]').forEach(el => {
    const iconName = el.getAttribute('data-realm-icon');
    if (window.REALM_ICONS && window.REALM_ICONS[iconName]) {
      el.innerHTML = window.REALM_ICONS[iconName];
    }
  });
}
window.renderRealmIcons = renderRealmIcons;

if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', renderRealmIcons);
} else {
  renderRealmIcons();
}
